/**
 * Escape untrusted text (step names, event names, segment values from imported
 * files) before interpolating it into ECharts HTML tooltip strings.
 */
export function escapeHtml(value: unknown): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
